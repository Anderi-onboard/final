/* 断法库 · 考试 / 求名        服务端 only(断法即产品,不进 assets/)
   ────────────────────────────────────────────────────────────────────────
   一条条目只有三格:

     id      程序拿它寻址
     原文    模型拿它讲话 —— 这一格不可再生,别的都可以
     机器值  只在程序真的要拿它做判断时才写。类型条目写「用神」,断法条目写
             「触发 + 断」,注解条目没有

   要不要多加一格,判据是:**模型拿着原文能不能自己得出它。能就不写。**
   唯一的例外是「必须每次都一样」的东西 —— 模型能得出 ≠ 每次都得出同一个,
   用神就是这一类,所以它写死。上线那副断错的盘死于用神由模型现场想。

   第一版这个文件每条有十二格(场景、判据、门槛、现实钩子、不许说…),九格是
   手写模型本来就会做的事。现实钩子尤其荒唐:那正是 M2-b 的全部工作,而且
   lei-xiang.json 的 38 个符号就在那儿等着被调。删掉的不是信息,是重复劳动。

   原文一律 owner 原话,不改写。改写就是把断法换成我对断法的转述,而转述没有出处。
*/

export const EXAM_ROLES = {
  self:    '世爻:考生自己(承受功名与成绩的主体)。',
  officer: '官鬼爻:功名、录取资格、及格线、名次、主考官。',
  parent:  '父母爻:文章、考卷、成绩、录取通知书、证书。',
  output:  '子孙爻:剥官之神 / 伤官之神(选拔考的第一大忌神)。',
  wealth:  '妻财爻:克文章之神(破坏考卷、导致发挥失常/涂改犯错的忌神)。',
  peer:    '兄弟爻:夺标之恶客(同考竞争者)。'
};

export const EXAM_TYPES = [
  { id: 'exam.type.selection',
    用神: ['officer', 'parent'],
    原文: '选拔性淘汰考(重名额):公务员国考/省考、事业编、研究生复试、竞争性抽签/竞聘。'
        + '主看官鬼爻(代表录取指标、名额、官位)。官鬼不旺或受克,绝无录取可能。' },

  { id: 'exam.type.pass',
    用神: ['parent', 'self'],
    原文: 'Pass 制 / 及格考(重过关):驾驶证、资格证(司法/医师/会计)、期末考、毕业答辩。'
        + '主看父母爻与世爻。父母(考卷/成绩)与世爻(自己)旺相无伤,即可过关。' },

  { id: 'exam.type.ranking',
    用神: ['officer', 'parent', 'peer'],
    原文: '争夺排名考(重名次):争夺状元、面试争第 1 名、选拔拔尖人才。'
        + '兼看兄弟爻。兄弟为竞争对手(「夺标之恶客」)。' }
];

/* 发给模型的:只有原文。三条一起发,让它自己挑并说明为什么 —— 不先分类再取一条,
   因为边界情况需要说得出「这题跨两类」(教资笔试是及格考、面试是排名考)。 */
export function typesForModel() {
  return EXAM_TYPES.map((t) => `[${t.id}] ${t.原文}`).join('\n\n');
}

export function rolesForModel() {
  return Object.values(EXAM_ROLES).join('\n');
}

/* 模型挑完 id,程序按 id 取用神。挑不到返回 null,不悄悄兜底成某一类 ——
   一个默认值和一个决定长得一模一样,这个仓库为此付过最贵的一次学费。 */
export function typeById(id) {
  return EXAM_TYPES.find((t) => t.id === id) || null;
}
