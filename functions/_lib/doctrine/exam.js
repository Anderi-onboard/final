/* 发给模型的那一份:只有它读得着的字段,结构字段不发(补集律 —— 程序算得出的
   不让模型再说一遍)。三条一起发,约 600 tok。 */
export function typesForModel() {
  return EXAM_TYPES.map((t) => [
    `[${t.id}] ${t.名}(重${t.重})`,
    `  常见:${t.场景.join('、')}`,
    `  断法原文:${t.原文}`,
    `  判据:${t.判据}`,
    `  门槛:${t.门槛}`,
    `  这一类里各角色代表什么:` + Object.entries(t.现实钩子)
      .map(([k, v]) => `\n    ${EXAM_ROLES[k].cn} = ${v}`).join(''),
    `  不许说:` + t.不许说.map((s) => `\n    - ${s}`).join('')
  ].join('\n')).join('\n\n');
}

/* 模型挑完 id 之后,程序按这个取结构字段。挑不到或挑了不存在的 id 时返回 null,
   由调用方决定怎么办 —— 不悄悄兜底成某一类。一个默认值和一个决定长得一模一样,
   这个仓库为此付过最贵的一次学费(每篇解读都锚在世爻上)。 */
export function typeById(id) {
  return EXAM_TYPES.find((t) => t.id === id) || null;
}
