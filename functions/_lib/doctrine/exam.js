/* 断法库 · 考试 / 求名
   ────────────────────────────────────────────────────────────────────────
   服务端 only。CLAUDE.md §2:「提示词栈就是产品本身,放在浏览器里等于开源它」——
   断法比提示词更是产品本身,所以它和 prompt-engine.js 住同一侧,不进 assets/。

   一条条目 = 一个来源,两个出口:

     结构字段(用神/忌神/gate)  → 程序读。用来算生克、跑裁决梯、点亮速断条。
                                 ⚠ 这些字段是人从原文里读出来写死的,不是正则
                                    算的,也不是模型运行时想的。用神一旦由模型
                                    现场决定,同一副盘两次跑会给出两个答案 ——
                                    上线那副断错的盘就是这么死的。

     原文 / 判据 / 门槛 / 现实钩子 → 模型读。用来解释、判分量、讲故事。
                                 ⚠ 只把结构字段发给模型,它只能复述结论;
                                    原文里的「为什么是这两个」「什么条件算成立」
                                    「门槛在哪」才是它讲得出话的地方。

   原文一律是 owner 提供的 SOP 原话,不改写、不缩写。改写就等于把断法换成了
   我对断法的转述,而那份转述没有出处。

   TYPES 三条一起发给模型(共 ~600 tok),让它自己挑并说明为什么 —— 不先分类
   再取一条。理由是边界:教师编既有名额又有及格线,教资笔试是及格考而面试是
   排名考。先分类就没地方说「这题跨两类」。模型挑的是 id,程序仍按那个 id 的
   结构字段走,所以确定性没丢。
*/

