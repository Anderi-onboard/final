/* Generate functions/_lib/relative-gloss.js from assets/xiangshu/lei-xiang.json.
   Run: node scripts/build-relative-gloss.mjs   (tests/relative-gloss.mjs checks it is current)

   WHY THIS EXISTS
   A 六亲 has one fixed meaning and many real referents. 兄弟 is always "same
   kind as me, takes a share" — but what takes a share depends entirely on what
   was asked. Buying something with crypto: the exchange's cut, the payment
   channel's fee, slippage. A relationship question: a rival, the friends who
   eat the time. A partnership: the co-founder, the broker, the distributor.

   The catalogue already holds all of it. 兄弟 carries nine facets, two of them
   `分利的 / whoever splits it` (合伙人, 中介, 抽成的渠道) and `耗费 / what eats
   it` (成本, 手续费、平台抽成). The crypto answer is sitting in the data.

   What was missing is the index: nothing selected WHICH facet is live for THIS
   question. chat-app.js fetches the catalogue for the 取象 panel — after the
   reading is written — and the server never read the file at all. So the model
   assembling a reading had never seen one item from it, and did the only thing
   left: named the label. Measured on a live reading, 2026-08-25: 兄弟 appeared
   six times, was the 用神, and was never once translated into anything real.

   THE SHAPE
     intension  — 兄弟 = 同我者、分我所有        → fixed, lives in the prompt
     extension  — the things it denotes           → the catalogue's facets
     index      — which facets this question lights up  → this file
   Only the third was absent, and without it the other two cannot meet.

   Facets are emitted once per relative and referenced by name, so the route map
   stays a list of names rather than a second copy of the items. */
import { readFileSync, writeFileSync } from 'node:fs';

const ROOT = new URL('..', import.meta.url).pathname.replace(/\/$/, '');
const cat = JSON.parse(readFileSync(`${ROOT}/assets/xiangshu/lei-xiang.json`, 'utf8'));

/* Which facets a route lights up, most apt first.

   Routes are not all the same kind of thing, and the map has to respect that.
   `relationship`, `intimacy`, `wealth` and `appearance` constrain the SUBJECT,
   so their lists are short and pointed. `timing` and `choice` constrain the
   QUESTION SHAPE and say nothing about what is being asked about — a timing
   question can be about money, a person, or a diagnosis — so they carry a wide
   set and let the reading choose. Narrowing those would be worse than the
   problem: it would push the model toward a facet the question never implied.

   Empty means "no preference recorded" and the reading gets every facet. */
const ROUTE_FACETS = {
  relationship: {
    /* 争夺 and 阻隔 first: the classic reading of 兄弟 here is the rival and the
       thing wedged in between. 同行's items are commercial (竞品, 抢客户的) —
       real for this symbol, wrong to lead with when the question is a person. */
    兄弟: ['争夺', '阻隔', '同辈', '同行'],
    妻财: ['女方', '钱'],
    官鬼: ['男方', '心魔', '压', '讼'],
    父母: ['长辈', '遮盖', '根基'],
    子孙: ['欢喜', '解厄']
  },
  intimacy: {
    兄弟: ['争夺', '阻隔', '同行'],
    妻财: ['女方'],
    官鬼: ['男方', '心魔', '压', '病'],
    父母: ['长辈', '遮盖'],
    子孙: ['欢喜', '解厄']
  },
  wealth: {
    兄弟: ['分利的', '耗费', '同行', '争夺'],
    妻财: ['钱', '货', '产业', '食禄', '凭据'],
    官鬼: ['职务', '上头', '讼', '压', '功名'],
    父母: ['文书', '平台', '根基', '车船', '操劳'],
    子孙: ['财源', '出品', '技术', '解厄']
  },
  appearance: {
    兄弟: ['同辈', '邻里'],
    妻财: ['女方', '器物', '货'],
    官鬼: ['男方', '功名', '病'],
    父母: ['长辈', '遮盖', '车船'],
    子孙: ['出品', '技术', '六畜']
  },
  future_unseen: {
    兄弟: ['同辈', '同行'],
    妻财: ['女方', '钱'],
    官鬼: ['男方', '功名', '职务'],
    父母: ['长辈', '根基', '学业'],
    子孙: ['晚辈', '欢喜', '出品']
  },
  // Shape-only routes: the subject is unknown, so do not pre-narrow it.
  timing: {},
  choice: {},
  general: {}
};

const LIUQIN = ['父母', '兄弟', '子孙', '妻财', '官鬼'];
const ITEM_CAP = 6;                    // enough to choose from, short enough to read

const facets = {};
for (const key of LIUQIN) {
  const sym = cat.symbols[key];
  if (!sym) throw new Error(`lei-xiang.json has no ${key}`);
  facets[key] = { en: sym.en, cats: {} };
  for (const c of sym.cats) {
    facets[key].cats[c.zh] = {
      en: c.en,
      zh: (c.items.zh || []).slice(0, ITEM_CAP),
      items_en: (c.items.en || []).slice(0, ITEM_CAP)
    };
  }
}

// A route may only name facets the catalogue actually has, or the gloss quietly
// emits nothing for that relative and we are back to a bare label.
for (const [route, byRelative] of Object.entries(ROUTE_FACETS)) {
  for (const [rel, names] of Object.entries(byRelative)) {
    for (const name of names) {
      if (!facets[rel] || !facets[rel].cats[name]) {
        throw new Error(`ROUTE_FACETS.${route}.${rel} names "${name}", which ${rel} does not have`);
      }
    }
  }
}

const out = `/* GENERATED by scripts/build-relative-gloss.mjs — do not edit by hand.
   Source: assets/xiangshu/lei-xiang.json (the catalogue is the only owner of
   these words). Regenerate after editing either the catalogue or the route map,
   and tests/relative-gloss.mjs will fail if this file has drifted from them.

   What this is for: a 六亲 means one thing and denotes many. This carries the
   many, indexed by what was asked, so the reading can name the real thing
   instead of printing the label. */
export const RELATIVE_FACETS = ${JSON.stringify(facets, null, 2)};

export const ROUTE_FACETS = ${JSON.stringify(ROUTE_FACETS, null, 2)};

/* Candidates for the relatives that are actually on this board, under this
   route. Returns [] when nothing applies, so the caller can leave the section
   out entirely rather than injecting an empty heading. */
export function relativeGloss(relativesOnBoard, route, lang) {
  const zh = lang === 'zh';
  const pref = ROUTE_FACETS[route] || {};
  const out = [];
  for (const rel of ${JSON.stringify(LIUQIN)}) {
    if (relativesOnBoard && relativesOnBoard.indexOf(rel) < 0) continue;
    const entry = RELATIVE_FACETS[rel];
    if (!entry) continue;
    const names = (pref[rel] && pref[rel].length) ? pref[rel] : Object.keys(entry.cats);
    const lines = [];
    for (const name of names) {
      const c = entry.cats[name];
      if (!c) continue;
      const items = zh ? c.zh : (c.items_en.length ? c.items_en : c.zh);
      if (!items.length) continue;
      lines.push((zh ? name : c.en) + ': ' + items.join('、'));
    }
    if (lines.length) out.push((zh ? rel : rel + ' (' + entry.en + ')') + ' — ' + lines.join(' | '));
  }
  return out;
}
`;

writeFileSync(`${ROOT}/functions/_lib/relative-gloss.js`, out);
const items = Object.values(facets).reduce((n, f) => n + Object.values(f.cats).reduce((m, c) => m + c.zh.length, 0), 0);
console.log(`relative-gloss built — ${LIUQIN.length} relatives, `
  + `${Object.values(facets).reduce((n, f) => n + Object.keys(f.cats).length, 0)} facets, `
  + `${items} items, ${Object.keys(ROUTE_FACETS).length} routes`);
